STEP_RELEVANCY_RUBRIC = """
실행 단계의 설명이 요구하는 작업에 대해, 실제 실행 결과가 해당 작업을
정확하게 수행했는지 다음 기준에 따라 평가하시오:

**1. 작업 완성도 (Task Completion)** [0-4점]:
- 4점: 단계에서 요구하는 작업이 완전히 완료됨. 모든 요소 포함
- 3점: 85-99% 정도 완료. 매우 부수적인 요소 하나 누락
- 2점: 70-84% 정도 완료. 일부 요소 누락이나 부분적 완성
- 1점: 50-69% 정도 완료. 상당 부분 미완성
- 0점: 50% 미만 또는 완전히 다른 작업 수행

**2. 결과 정확성 (Result Accuracy)** [0-3점]:
- 3점: 결과가 정확함. 오류 없음
- 2점: 결과가 대체로 정확하나 경미한 오류 존재 (오타, 단위 오류 등)
- 1점: 결과에 중간 수준의 오류 (계산 실수, 데이터 누락 등)
- 0점: 결과가 부정확함. 심각한 오류 또는 거짓 정보

**3. 형식 적절성 (Format Appropriateness)** [0-2점]:
- 2점: 결과가 단계에서 요구하는 형식으로 제시됨 (표, 목록, 수치 등)
- 1점: 형식이 대체로 맞으나 약간의 구성 문제
- 0점: 형식이 부적절함. 요구와 다른 형식

**총점 계산:**
총점(0-9) = 작업완성도(0-4) + 결과정확성(0-3) + 형식적절성(0-2)
최종 점수 = 총점 / 9 (0.0-1.0 스케일로 정규화)
"""

