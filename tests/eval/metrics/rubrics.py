KEY_FACTS_QUALITY_RUBRIC = """
리뷰 단계에서 추출한 key_facts가 multi-turn 대화에서 유용하게 활용될 수
있는 정보인지 다음 기준에 따라 평가하시오:

**1. 정보 가치 (Information Value)** [0-3점]:
- 3점: 추출된 facts가 이후 질문에 직접 참고할 수 있는 구체적 정보
- 2점: 대부분 유용하나 일부 facts는 추상적이거나 덜 중요함
- 1점: 일부만 유용. 많은 facts가 불완전하거나 불명확
- 0점: 거의 유용하지 않음. 중복되거나 무의미한 정보

**2. 구체성 (Specificity)** [0-3점]:
- 3점: 모든 facts가 구체적. 숫자, 이름, 날짜 등 명확한 정보 포함
- 2점: 대부분 구체적이나 일부 추상적 표현
- 1점: 추상적 표현이 많음. "좋다", "크다" 같은 모호한 형용사 사용
- 0점: 매우 추상적. 실질 정보 거의 없음

**3. 완전성 (Completeness)** [0-2점]:
- 2점: 답변의 핵심 정보가 모두 포함됨
- 1점: 대부분 포함되나 일부 중요 정보 누락
- 0점: 상당 부분 누락. 불완전한 정보

**총점 계산:**
총점(0-8) = 정보가치(0-3) + 구체성(0-3) + 완전성(0-2)
최종 점수 = 총점 / 8 (0.0-1.0 스케일로 정규화)
"""

ANSWER_QUALITY_RUBRIC = """
최종 답변이 사용자의 요청에 얼마나 잘 대응했는지 다음 기준에 따라
평가하시오:

**1. 관련성 (Relevance)** [0-3점]:
- 3점: 답변이 요청과 완벽하게 관련. 모든 측면 다룸
- 2점: 대체로 관련 있으나 일부 부분이 다소 벗어남
- 1점: 기본적으로는 관련 있으나 상당 부분 불충분하거나 벗어남
- 0점: 거의 관련 없음. 완전히 다른 주제 또는 무의미한 답변

**2. 충분성 (Sufficiency)** [0-3점]:
- 3점: 답변이 충분히 상세하고 완전함
- 2점: 대부분 충분하나 일부 세부 사항 부족
- 1점: 기본 정보만 있고 충분하지 않음
- 0점: 매우 불충분. 거의 정보 없음

**3. 명확성 (Clarity)** [0-2점]:
- 2점: 답변이 명확하고 이해하기 쉬움
- 1점: 대체로 명확하나 일부 표현이 모호함
- 0점: 명확하지 않음. 혼동하기 쉬운 답변

**총점 계산:**
총점(0-8) = 관련성(0-3) + 충분성(0-3) + 명확성(0-2)
최종 점수 = 총점 / 8 (0.0-1.0 스케일로 정규화)
"""


