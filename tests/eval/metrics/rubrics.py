PLAN_DECOMPOSITION_RUBRIC = """
다음 기준에 따라 0-10점으로 평가하시오:

**1. 독립성 (Independence)** [0-3점]:
- 3점: 각 단계가 명확히 분리되고 독립적으로 실행 가능함. 단계 간 순환 의존성 없음
- 2점: 대부분의 단계가 독립적이나 일부 의존성이 모호함
- 1점: 단계 간 의존성이 불명확하거나 일부 순환 의존성 존재
- 0점: 단계들이 뒤섞여 있거나 독립적으로 실행 불가능함

**2. 구체성 (Specificity)** [0-3점]:
- 3점: 모든 단계가 구체적인 행동을 명시 (어떤 도구 사용, 어떤 데이터 처리 등)
- 2점: 대부분의 단계가 구체적이나 일부 추상적인 표현 있음
- 1점: 절반 이상의 단계가 모호하거나 추상적 ("정보를 수집한다" 같은 표현)
- 0점: 단계들이 전반적으로 모호하고 구체적 행동 명시 부족

**3. 논리적 순서 (Logical Flow)** [0-2점]:
- 2점: 단계 순서가 완벽히 논리적이고 효율적. 의존성 관계가 올바르게 반영됨
- 1점: 순서가 대체로 타당하나 일부 최적화 필요. 약간의 비효율 있음
- 0점: 단계 순서가 비논리적이거나 심각한 비효율 존재. 실행 불가능한 순서

**4. 도구 선택 (Tool Selection)** [0-2점]:
- 2점: 각 단계에 적절한 도구가 명확히 지정됨. 도구 선택이 최적
- 1점: 도구 선택이 대체로 적절하나 더 적합한 도구 있을 가능성
- 0점: 부적절한 도구 선택 또는 도구 미지정. 해결 불가능한 도구 선택

**총점 계산:**
총점(0-10) = 독립성(0-3) + 구체성(0-3) + 논리적순서(0-2) + 도구선택(0-2)
최종 점수 = 총점 / 10 (0.0-1.0 스케일)
"""

PLAN_COMPLETENESS_RUBRIC = """
주어진 사용자 요청을 완전히 달성하기 위해 필요한 모든 단계가 포함되었는지
다음 기준에 따라 평가하시오:

**1. 핵심 단계 포함 (Essential Steps)** [0-3점]:
- 3점: 요청 달성에 필수적인 모든 단계가 포함됨
- 2점: 95% 이상의 필수 단계 포함. 매우 부수적인 단계 하나 누락 가능
- 1점: 80-94% 정도의 필수 단계 포함. 여러 부수 단계 또는 중요 단계 일부 누락
- 0점: 80% 미만의 필수 단계 포함. 핵심 단계 누락

**2. 중복 제거 (No Redundancy)** [0-2점]:
- 2점: 불필요한 중복 단계 없음. 효율적인 구성
- 1점: 미미한 수준의 중복 존재 (같은 작업이 여러 단계에서 반복)
- 0점: 명백한 중복 단계 존재. 과도한 반복

**3. 분기점 처리 (Conditional Branches)** [0-2점]:
- 2점: 필요한 모든 분기 상황을 고려. "만약 X이면 Y하고, 그렇지 않으면 Z" 형태로 구분
- 1점: 주요 분기는 고려했으나 일부 예외 상황 미처리
- 0점: 분기 상황 미고려. "항상" 한 방식으로만 진행

**총점 계산:**
총점(0-7) = 핵심단계(0-3) + 중복제거(0-2) + 분기점(0-2)
최종 점수 = 총점 / 7 (0.0-1.0 스케일로 정규화)
"""

